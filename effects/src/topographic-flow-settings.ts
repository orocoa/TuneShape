export function validateTopographicFlow(value:unknown):TopographicFlowSettings{
 if(!value||typeof value!=='object'||Object.getPrototypeOf(value)!==Object.prototype)throw Error('地形设置必须是普通数据。');const s=value as Record<string,unknown>,keys=Object.keys(defaultTopographicFlow);
 if(Reflect.ownKeys(s).length!==keys.length||keys.some(k=>!Object.hasOwn(Object.getOwnPropertyDescriptor(s,k)??{},'value')))throw Error('地形字段不完整或含未知字段。');
 for(const c of topographicNumberControls)if(typeof s[c.key]!=='number'||!Number.isFinite(s[c.key])||Number(s[c.key])<c.min||Number(s[c.key])>c.max)throw Error(c.zh+'超出范围。');
 if(!Number.isInteger(s.seed)||!Number.isInteger(s.density))throw Error('种子和密度须为整数。');
 for(const k of ['gradientEnabled','hoverEnabled','animateEntrance','paused'])if(typeof s[k]!=='boolean')throw Error('地形开关设置无效。');
 for(const [key,values] of [['lineStyle',['solid','mixed','dashed']],['hoverEffect',['rings','spread','swirl','ripple','drag']],['hoverDirection',['push','pull']]] as const)if(!values.includes(s[key] as never))throw Error('地形选项无效。');
 for(const key of ['backgroundColor','lineColor','accentColor'])if(typeof s[key]!=='string'||!/^#[0-9a-f]{6}$/i.test(String(s[key])))throw Error('颜色须为六位十六进制。');
 const colors=s.gradientColors;if(!Array.isArray(colors)||Object.getPrototypeOf(colors)!==Array.prototype||colors.length<2||colors.length>8||Reflect.ownKeys(colors).length!==colors.length+1)throw Error('高程渐变须有 2–8 个颜色。');
 for(let i=0;i<colors.length;i++)if(!Object.hasOwn(Object.getOwnPropertyDescriptor(colors,String(i))??{},'value')||typeof colors[i]!=='string'||!/^#[0-9a-f]{6}$/i.test(colors[i]))throw Error('高程颜色无效。');
 return structuredClone(s) as TopographicFlowSettings;
}
